// Generates src/schema.ts from migrations/*.sql.
//
// Why: the Worker needs the DDL at runtime so a freshly deployed instance can
// create its own tables (nobody wants to run `wrangler d1 migrations apply`
// before the first page load). migrations/*.sql stays the single source of
// truth — this script just turns those files into a string array the bundler
// can inline.
//
// Run via `pnpm run build` (it is the first step) or `node tools/build-schema.mjs`.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const migrationsDir = path.join(root, 'migrations');
const outFile = path.join(root, 'src', 'schema.ts');

const files = fs
  .readdirSync(migrationsDir)
  .filter((f) => f.endsWith('.sql'))
  .sort();

if (!files.length) {
  console.error('build-schema: no .sql files found in migrations/');
  process.exit(1);
}

const statements = [];
for (const file of files) {
  const raw = fs.readFileSync(path.join(migrationsDir, file), 'utf8');
  // Strip line comments, then split on semicolons. The migration files contain
  // no `--` inside string literals, so a plain strip is safe here.
  const stripped = raw
    .split('\n')
    .map((line) => line.replace(/--.*$/, ''))
    .join('\n');
  for (const part of stripped.split(';')) {
    const sql = part.replace(/\s+/g, ' ').trim();
    if (sql) statements.push(sql);
  }
}

const body = statements.map((s) => `  ${JSON.stringify(s)},`).join('\n');
const content = `// AUTO-GENERATED by tools/build-schema.mjs from migrations/*.sql.
// Do not edit by hand: change the migration file, then run \`pnpm run build\`.
//
// These statements are idempotent (CREATE TABLE IF NOT EXISTS / INSERT OR
// IGNORE), so applying them to an already-migrated database is a no-op. That is
// what makes the runtime auto-migration in src/migrate.ts safe.

export const SCHEMA_SOURCE_FILES: readonly string[] = ${JSON.stringify(files)};

export const SCHEMA_STATEMENTS: readonly string[] = [
${body}
];
`;

fs.writeFileSync(outFile, content, 'utf8');
console.log(`build-schema: ${statements.length} statements from ${files.length} migration(s) -> src/schema.ts`);
